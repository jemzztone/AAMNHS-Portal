<?php

namespace App\Http\Middleware;

use Illuminate\Http\Request;
use Inertia\Middleware;
use Tighten\Ziggy\Ziggy;

class HandleInertiaRequests extends Middleware
{
    /**
     * The root template that is loaded on the first page visit.
     *
     * @var string
     */
    protected $rootView = 'app';

    /**
     * Determine the current asset version.
     */
    public function version(Request $request): ?string
    {
        return parent::version($request);
    }

    /**
     * Define the props that are shared by default.
     *
     * @return array<string, mixed>
     */
    public function share(Request $request): array
    {
        return [
            ...parent::share($request),
            'auth' => [
                'user' => $request->user(),
            ],
            // One-request flash messages: success/error banners plus rich
            // payloads (import results, generated passwords) shown once.
            'flash' => [
                'success' => fn () => $request->session()->get('success'),
                'error' => fn () => $request->session()->get('error'),
                'status' => fn () => $request->session()->get('status'),
                'reset_password' => fn () => $request->session()->get('reset_password'),
                'import_result' => fn () => $request->session()->get('import_result'),
            ],
            'features' => [
                // Check if XLSX import is fully supported (requires both ZipArchive and PhpSpreadsheet)
                'xlsx_supported' => class_exists('ZipArchive')
                    && class_exists('PhpOffice\PhpSpreadsheet\IOFactory'),
            ],
            'ziggy' => fn () => [
                ...(new Ziggy)->toArray(),
                'location' => $request->url(),
            ],
        ];
    }
}
